    "      background: #fafaf9;",
    "      color: #1c1917;",
    "      line-height: 1.55;",
    "    }",
    "    .wrap { max-width: 860px; margin: 0 auto; padding: 40px 20px 64px; }",
    "    h1 { font-size: 1.6rem; letter-spacing: -0.03em; margin: 0 0 8px; font-weight: 650; }",
    "    .meta { color: #78716c; font-size: 0.92rem; margin-bottom: 28px; }",
    "    .player { margin-bottom: 32px; }",
    "    .player-frame {",
    "      position: relative;",
    "      width: 100%;",
    "      padding-bottom: 56.25%;",
    "      background: #e7e5e4;",
    "      border-radius: 10px;",
    "      overflow: hidden;",
    "      border: 1px solid #e7e5e4;",
    "    }",
    "    .player-frame iframe {",
    "      position: absolute;",
    "      inset: 0;",
    "      width: 100%;",
    "      height: 100%;",
    "      border: 0;",
    "    }",
    "    .player-link { margin: 10px 0 0; font-size: 0.88rem; }",
    "    .player-link a { color: #44403c; }",
    "    h2 { font-size: 1.05rem; margin: 0 0 12px; font-weight: 600; }",
    "    .transcript {",
    "      background: #fff;",
    "      border: 1px solid #e7e5e4;",
    "      border-radius: 10px;",
    "      padding: 20px 22px;",
    "      white-space: pre-wrap;",
    "      font-size: 0.95rem;",
    "      color: #292524;",
    "    }",
    "    footer { margin-top: 36px; color: #a8a29e; font-size: 0.8rem; }",
    "    footer a { color: #78716c; }",
    "  </style>",
    "</head>",
